#[test]
fn legacy_memory_past_rom_is_minus_one() {
    let mut legacy = Memory::new_legacy(0x100);
    legacy.load_rom(&[0x2a]).unwrap();
    assert_eq!(legacy.read(0x100).unwrap(), -1);

    let mut zero = Memory::new(0x100);
    zero.load_rom(&[0x2a]).unwrap();
    assert_eq!(zero.read(0x100).unwrap(), 0);
}

#[test]
fn entry_trampoline_allows_data_first_programs() {
    let source = r#""data at the front"
[main]
mov 0x00 0x00 0x01 0x00 0x00 0x00 0x00 0x48
mov 0x00 0x00 0x01 0x01 0x00 0x00 0x01 0x00
putc 0x00 0x00 0x01 0x01
exit
"#;
    let source = Source::new("<entry-test>", source.as_bytes().to_vec());
    let options = CompileOptions {
        raw_strings: true,
        entry: Some("main".to_owned()),
        assemble: AssembleOptions {
            target: Target::Legacy,
            verify: VerifyLevel::Off,
            ..AssembleOptions::default()
        },
    };
    let artifact = compile(&source, &options).expect("compile");
    let mut output = Vec::new();
    let outcome = {
        let mut vm = Vm::new(
            Memory::new(0x8000),
            Cursor::new(Vec::new()),
            &mut output,
            VmOptions::default(),
        );
        vm.load_rom(&artifact.bytes).expect("load");
        vm.run().expect("run")
    };
    assert_eq!(String::from_utf8(output).unwrap(), "H");
    assert_eq!(outcome.reason, ExitReason::Exit);
}

