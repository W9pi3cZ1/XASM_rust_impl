use std::io::Cursor;

use xasm_core::assembler::{AssembleOptions, Target, VerifyLevel};
use xasm_core::{compile, CompileOptions, Source};
use xasm_vm::{ExitReason, Memory, RunOutcome, Vm, VmError, VmOptions};

fn assemble(source: &str, target: Target) -> Vec<u8> {
    let source = Source::new("<vm-test>", source.as_bytes().to_vec());
    let options = CompileOptions {
        raw_strings: true,
        entry: None,
        assemble: AssembleOptions {
            target,
            verify: VerifyLevel::Off,
            ..AssembleOptions::default()
        },
    };
    compile(&source, &options)
        .unwrap_or_else(|report| panic!("assembly failed:\n{}", report.render(&source)))
        .bytes
}

fn run_with(
    source: &str,
    target: Target,
    input: &[u8],
    options: VmOptions,
) -> (String, RunOutcome) {
    let rom = assemble(source, target);
    let mut output = Vec::new();
    let outcome = {
        let mut vm = Vm::new(
            Memory::new(0x8000),
            Cursor::new(input.to_vec()),
            &mut output,
            options,
        );
        vm.load_rom(&rom).expect("load rom");
        vm.run().expect("run rom")
    };
    (String::from_utf8(output).expect("utf-8 output"), outcome)
}

fn run(source: &str, target: Target, input: &[u8]) -> (String, RunOutcome) {
    run_with(source, target, input, VmOptions::default())
}

const HELLO_CELLS: &str = "\
mov 0x00 0x00 0x01 0x00 0x00 0x00 0x00 0x48
mov 0x00 0x00 0x01 0x01 0x00 0x00 0x01 0x00
putc 0x00 0x00 0x01 0x01
exit
";

#[test]
fn prints_a_character() {
    let (output, outcome) = run(HELLO_CELLS, Target::Legacy, b"");
    assert_eq!(output, "H");
    assert_eq!(outcome.reason, ExitReason::Exit);
}

