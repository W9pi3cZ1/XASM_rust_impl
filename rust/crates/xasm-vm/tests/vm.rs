#[test]
fn unknown_opcodes_follow_legacy_or_strict_mode() {
    let rom = [0x99u8, 0x2a];
    let mut output = Vec::new();
    {
        let mut vm = Vm::new(
            Memory::new(0x100),
            Cursor::new(Vec::new()),
            &mut output,
            VmOptions::default(),
        );
        vm.load_rom(&rom).unwrap();
        let outcome = vm.run().unwrap();
        assert_eq!(outcome.reason, ExitReason::Exit);
    }

    let mut output = Vec::new();
    let mut vm = Vm::new(
        Memory::new(0x100),
        Cursor::new(Vec::new()),
        &mut output,
        VmOptions {
            strict_unknown: true,
            ..VmOptions::default()
        },
    );
    vm.load_rom(&rom).unwrap();
    assert!(matches!(
        vm.run(),
        Err(VmError::UnknownOpcode {
            pc: 0,
            opcode: 0x99
        })
    ));
}

